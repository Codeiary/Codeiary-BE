CREATE TABLE github_blog_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    claim_version INTEGER NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_github_blog_outbox_event_type CHECK (event_type IN ('CREATED', 'UPDATED', 'DELETED')),
    CONSTRAINT ck_github_blog_outbox_status CHECK (status IN ('PENDING', 'ENQUEUED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_github_blog_outbox_claim_version CHECK (claim_version >= 0),
    CONSTRAINT ck_github_blog_outbox_failure_count CHECK (failure_count >= 0)
);

CREATE INDEX idx_github_blog_outbox_status_retry
    ON github_blog_outbox (status, next_attempt_at, id);
