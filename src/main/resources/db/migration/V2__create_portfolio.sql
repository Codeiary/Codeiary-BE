CREATE TABLE font (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    css_family VARCHAR(500) NOT NULL,
    stylesheet_url VARCHAR(2048),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_font_code UNIQUE (code)
);

CREATE TABLE portfolio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    title_align VARCHAR(10) NOT NULL DEFAULT 'LEFT',
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    default_font_id BIGINT NOT NULL REFERENCES font(id) ON DELETE RESTRICT,
    representative_image_url VARCHAR(2048),
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_portfolio_title_alignment CHECK (title_align IN ('LEFT', 'CENTER', 'RIGHT'))
);

CREATE INDEX idx_portfolio_author_created_id ON portfolio(author_id, created_at DESC, id DESC);
CREATE INDEX idx_portfolio_public_created_id ON portfolio(created_at DESC, id DESC) WHERE is_public = TRUE;

CREATE TABLE portfolio_title_style (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolio(id) ON DELETE CASCADE,
    font_id BIGINT REFERENCES font(id) ON DELETE RESTRICT,
    start_offset INTEGER NOT NULL,
    end_offset INTEGER NOT NULL,
    font_size DOUBLE PRECISION,
    text_color VARCHAR(7),
    CONSTRAINT ck_portfolio_title_style_range CHECK (start_offset >= 0 AND start_offset < end_offset),
    CONSTRAINT ck_portfolio_title_style_size CHECK (font_size IS NULL OR font_size BETWEEN 10 AND 96),
    CONSTRAINT ck_portfolio_title_style_color CHECK (text_color IS NULL OR text_color ~ '^#[0-9a-fA-F]{6}$')
);

CREATE INDEX idx_portfolio_title_style_start ON portfolio_title_style(portfolio_id, start_offset);

CREATE TABLE portfolio_block (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolio(id) ON DELETE CASCADE,
    block_type VARCHAR(20) NOT NULL,
    sort_order INTEGER NOT NULL,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    width_px DOUBLE PRECISION NOT NULL,
    height_px DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_portfolio_block_order UNIQUE (portfolio_id, sort_order) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_portfolio_block_type CHECK (block_type IN ('TEXT', 'IMAGE')),
    CONSTRAINT ck_portfolio_block_order CHECK (sort_order >= 0),
    CONSTRAINT ck_portfolio_block_position CHECK (x >= 0 AND y >= 0 AND width_px > 0),
    CONSTRAINT ck_portfolio_block_height CHECK (height_px > 0)
);

CREATE TABLE portfolio_text_block (
    block_id BIGINT PRIMARY KEY REFERENCES portfolio_block(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    text_align VARCHAR(10) NOT NULL DEFAULT 'LEFT',
    CONSTRAINT ck_portfolio_text_alignment CHECK (text_align IN ('LEFT', 'CENTER', 'RIGHT'))
);

CREATE TABLE portfolio_image_block (
    block_id BIGINT PRIMARY KEY REFERENCES portfolio_block(id) ON DELETE CASCADE,
    image_url VARCHAR(2048) NOT NULL,
    image_alt VARCHAR(1000)
);

CREATE TABLE portfolio_text_style (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text_block_id BIGINT NOT NULL REFERENCES portfolio_text_block(block_id) ON DELETE CASCADE,
    font_id BIGINT REFERENCES font(id) ON DELETE RESTRICT,
    start_offset INTEGER NOT NULL,
    end_offset INTEGER NOT NULL,
    font_size DOUBLE PRECISION,
    text_color VARCHAR(7),
    CONSTRAINT ck_portfolio_text_style_range CHECK (start_offset >= 0 AND start_offset < end_offset),
    CONSTRAINT ck_portfolio_text_style_size CHECK (font_size IS NULL OR font_size BETWEEN 10 AND 96),
    CONSTRAINT ck_portfolio_text_style_color CHECK (text_color IS NULL OR text_color ~ '^#[0-9a-fA-F]{6}$')
);

CREATE INDEX idx_portfolio_text_style_block_start ON portfolio_text_style(text_block_id, start_offset);

